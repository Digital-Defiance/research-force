import { getTableColumns, getTableName } from 'drizzle-orm';
import type { SQLiteTable } from 'drizzle-orm/sqlite-core';
import { BUILT_IN_ROLES } from '@researchforce/domain/permissions';
import { SETTINGS } from '@researchforce/domain/settings';
import type { SettingKey } from '@researchforce/domain/settings';
import { configValues, counters, methodsTerms, policyPages, policySections, POLICY_PAGE_KEYS, rolePermissions, roles, settings } from '../schema/core';
import { FIXED_METHODS_TERMS } from './methods-descriptions';
import { SEED_POLICY_SECTIONS } from './policy-sections';
import { SEED_VALUES } from './value-sets';

/** Stands for the time the migration is applied, as an ISO 8601 UTC timestamp with milliseconds. */
const APPLIED_AT = Symbol('applied at');
const APPLIED_AT_SQL = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";
type SeedRow<T extends SQLiteTable> = { readonly [K in keyof T['$inferInsert']]: T['$inferInsert'][K] | typeof APPLIED_AT };

function literal(value: unknown): string {
  if (value === APPLIED_AT) return APPLIED_AT_SQL;
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  throw new TypeError(`Seed values must be strings, safe integers, or NULL: ${String(value)}`);
}

/** One INSERT per table, with values mapped through each column's own driver mapping (JSON, booleans). */
function insert<T extends SQLiteTable>(table: T, rows: readonly SeedRow<T>[]): string {
  const columns = getTableColumns(table);
  const keys = Object.keys(columns).filter((key) => rows.some((row) => Object.hasOwn(row, key)));
  const values = rows.map((row) => `(${keys.map((key) => {
    const value = (row as Record<string, unknown>)[key];
    return literal(value === APPLIED_AT || value === undefined || value === null ? value : columns[key]!.mapToDriverValue(value));
  }).join(', ')})`);
  return `INSERT INTO \`${getTableName(table)}\` (${keys.map((key) => `\`${columns[key]!.name}\``).join(', ')}) VALUES\n${values.join(',\n')};`;
}

const SEEDED_SETTINGS = (Object.keys(SETTINGS) as SettingKey[]).filter((key) => key !== 'responsiblePerson');

/**
 * The seed migration for rf-core. Everything here is the same for every installation; installation
 * identity, the first Administrator, the Responsible_Person, the first Project, and the Content_Licence
 * are bootstrap inputs (design "Product and installation boundary"). The test that compares this text
 * with migrations/core/0002_seed.sql regenerates the file with `vitest -u`.
 */
export function seedSql(): string {
  const statements = [
    insert(counters, [{ k: 'change', v: 0 }, { k: 'frozen', v: 0 }]),
    insert(roles, Object.values(BUILT_IN_ROLES).map((role) => ({ id: role.id, name: role.name, nameKey: role.name.toLowerCase(), builtin: true, rev: 1, updatedSeq: 0 }))),
    insert(rolePermissions, Object.values(BUILT_IN_ROLES).flatMap((role) => Object.entries(role.permissions)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([permission, scope]) => ({ roleId: role.id, permission: permission as typeof rolePermissions.$inferInsert['permission'], scope: scope as typeof rolePermissions.$inferInsert['scope'] })))),
    insert(configValues, SEED_VALUES.map((value) => ({
      id: value.id, setKey: value.setKey, name: value.name, nameKey: value.name.toLowerCase(), retired: false, locked: value.locked,
      permitsPublication: value.permitsPublication, position: value.position, publicDescription: value.publicDescription, rev: 1, updatedSeq: 0,
    }))),
    insert(methodsTerms, FIXED_METHODS_TERMS.map((term, position) => ({ ...term, position, rev: 1, updatedSeq: 0 }))),
    insert(settings, SEEDED_SETTINGS.map((key) => ({ key, value: SETTINGS[key].default, updatedAt: APPLIED_AT, updatedSeq: 0 }))),
    insert(policyPages, POLICY_PAGE_KEYS.map((pageKey) => ({ pageKey, sectionsChangedAt: APPLIED_AT, rev: 1, updatedSeq: 0 }))),
    insert(policySections, POLICY_PAGE_KEYS.flatMap((pageKey) => SEED_POLICY_SECTIONS.filter((section) => section.pageKey === pageKey).map((section, position) => ({
      pageKey, sectionKey: section.sectionKey, position, title: section.title, required: section.required, text: section.text, textSpans: [], changedAt: APPLIED_AT,
    })))),
  ];
  return `-- Generated by packages/db/src/seed/seed.ts. Do not edit; run \`npx vitest --run -u packages/db\` after changing the seed modules.\n${statements.join('\n--> statement-breakpoint\n')}\n`;
}
